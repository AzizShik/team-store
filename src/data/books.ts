let coverModules: Record<string, string> | undefined;

export const coverUrl = (book: Book): string => {
  coverModules ??= import.meta.glob('../assets/covers/*.jpg', {
    eager: true,
    query: '?url',
    import: 'default',
  }) as Record<string, string>;

  return coverModules[`../assets/covers/${book.id}.jpg`] ?? '';
};

